import { build } from 'esbuild';
import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const result = await build({ entryPoints: [fileURLToPath(new URL('./src/index.tsx', import.meta.url))], bundle: true, write: false, format: 'iife', target: 'chrome110', minify: true, define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.css': 'text' } });
const destination = new URL('../../apps/mobile/src/generated/', import.meta.url);
await mkdir(destination, { recursive: true });
await writeFile(new URL('tavernBundle.ts', destination), '// Generated by @st/web-ui; do not edit.\nexport const tavernBundle = ' + JSON.stringify(result.outputFiles[0].text) + ';\n');
